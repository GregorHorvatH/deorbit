"""Builds the terrain data modules from Natural Earth (public domain, https://www.naturalearthdata.com).

Run:  python3 -I scripts/build_terrain.py <directory with the Natural Earth GeoJSON files>

Reads (only as JSON, nothing in that directory is executed):
  ne_50m_land, ne_50m_lakes, ne_50m_rivers_lake_centerlines, ne_50m_glaciated_areas, ne_50m_geography_regions_polys
Writes src/render/data/{land,lakes,rivers,deserts,glaciers}.ts: simplified (Douglas-Peucker) and rounded to 0.01 degree,
as flat [lon, lat, lon, lat, ...] arrays. Standard library only."""

import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "render", "data")


def perp(p, a, b):
    """Distance from p to the segment a-b (degrees, flat)."""
    dx, dy = b[0] - a[0], b[1] - a[1]
    l2 = dx * dx + dy * dy
    if l2 == 0:
        return math.hypot(p[0] - a[0], p[1] - a[1])
    t = max(0.0, min(1.0, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l2))
    return math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)


def rdp(pts, eps):
    """Douglas-Peucker on an open polyline (iterative, so long coasts do not hit the recursion limit)."""
    if len(pts) < 3:
        return pts[:]
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        i, j = stack.pop()
        far, fi = 0.0, -1
        for k in range(i + 1, j):
            d = perp(pts[k], pts[i], pts[j])
            if d > far:
                far, fi = d, k
        if fi >= 0 and far > eps:
            keep[fi] = True
            stack += [(i, fi), (fi, j)]
    return [p for p, k in zip(pts, keep) if k]


def simplify_ring(ring, eps):
    """A closed ring (first == last): split at the point farthest from the start so it cannot collapse to a line."""
    pts = ring[:-1] if ring[0] == ring[-1] else ring[:]
    if len(pts) < 4:
        return None
    k = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
    a = rdp(pts[: k + 1], eps)
    b = rdp(pts[k:] + [pts[0]], eps)
    out = a[:-1] + b[:-1]
    return out if len(out) >= 3 else None


def area(ring):
    return abs(sum(ring[i - 1][0] * ring[i][1] - ring[i][0] * ring[i - 1][1] for i in range(len(ring)))) / 2


def flat(pts):
    out = []
    for lon, lat in pts:
        out += [round(lon, 2), round(lat, 2)]
    return out


def polygons(feature):
    g = feature["geometry"]
    if g["type"] == "Polygon":
        return [g["coordinates"]]
    if g["type"] == "MultiPolygon":
        return g["coordinates"]
    return []


def lines(feature):
    g = feature["geometry"]
    if g["type"] == "LineString":
        return [g["coordinates"]]
    if g["type"] == "MultiLineString":
        return g["coordinates"]
    return []


def poly_rings(poly, eps, min_area):
    """[outline, hole, hole...] simplified; None when the outline is too small to matter."""
    rings = []
    for n, r in enumerate(poly):
        s = simplify_ring(r, eps)
        if s is None or area(s) < (min_area if n == 0 else min_area * 2):
            if n == 0:
                return None
            continue
        rings.append(flat(s))
    return rings


def write_ts(name, doc, decl, rows):
    os.makedirs(OUT, exist_ok=True)
    body = ",\n".join("  " + json.dumps(r, separators=(",", ":")) for r in rows)
    with open(os.path.join(OUT, name + ".ts"), "w") as f:
        f.write("// GENERATED by scripts/build_terrain.py from Natural Earth (public domain) - do not edit by hand.\n")
        f.write("/** %s */\nexport const %s = [\n%s,\n]\n" % (doc, decl, body))
    return os.path.getsize(os.path.join(OUT, name + ".ts"))


def main(src):
    def load(n):
        with open(os.path.join(src, n + ".geojson")) as f:
            return json.load(f)["features"]

    report = {}

    # ---- land: polygons as [outline, ...holes], each ring flat lon/lat
    land = []
    for ft in load("ne_50m_land"):
        for poly in polygons(ft):
            r = poly_rings(poly, 0.07, 0.05)  # tiny islands (< ~0.05 sq. degree) are not worth a pixel
            if r:
                land.append(r)
    land.sort(key=lambda r: -len(r[0]))
    report["land"] = (len(land), sum(len(x) // 2 for r in land for x in r),
                      write_ts("land", "Land: polygons of rings (the first ring is the outline, the others are holes); each ring is a flat [lon, lat, ...] array in degrees.",
                               "LAND: ReadonlyArray<ReadonlyArray<ReadonlyArray<number>>>", land))

    # ---- lakes and inland seas: polygons to cut out of the land
    lakes = []
    for ft in load("ne_50m_lakes"):
        rank = ft["properties"].get("scalerank")
        if rank is None or rank > 1:  # note: rank 0 is the biggest lakes, so do not test it for truthiness
            continue
        for poly in polygons(ft):
            r = poly_rings(poly, 0.04, 0.12)
            if r:
                lakes.append(r)
    report["lakes"] = (len(lakes), sum(len(x) // 2 for r in lakes for x in r),
                       write_ts("lakes", "Lakes and inland seas: polygons of rings, like LAND.", "LAKES: ReadonlyArray<ReadonlyArray<ReadonlyArray<number>>>", lakes))

    # ---- rivers: polylines with a rank (1 = the biggest)
    rivers = []
    for ft in load("ne_50m_rivers_lake_centerlines"):
        p = ft["properties"]
        rank = p.get("scalerank")
        if rank is None or rank > 4 or p.get("featurecla") != "River":
            continue
        for ln in lines(ft):
            s = rdp([tuple(c[:2]) for c in ln], 0.05)
            if len(s) >= 2:
                rivers.append({"rank": rank, "name": p.get("name_en") or p.get("name") or "", "pts": flat(s)})
    report["rivers"] = (len(rivers), sum(len(r["pts"]) // 2 for r in rivers),
                        write_ts("rivers", "Rivers: a rank (1 = the biggest), a name and a flat [lon, lat, ...] polyline in degrees.", "RIVERS: ReadonlyArray<{ rank: number; name: string; pts: ReadonlyArray<number> }>", rivers))

    # ---- deserts and glaciers: single outlines
    deserts = []
    for ft in load("ne_50m_geography_regions_polys"):
        if ft["properties"].get("FEATURECLA") != "Desert":
            continue
        for poly in polygons(ft):
            r = poly_rings(poly[:1], 0.12, 0.3)
            if r:
                deserts.append(r[0])
    report["deserts"] = (len(deserts), sum(len(r) // 2 for r in deserts),
                         write_ts("deserts", "Deserts: one outline each, a flat [lon, lat, ...] array in degrees.", "DESERTS: ReadonlyArray<ReadonlyArray<number>>", deserts))

    glaciers = []
    for ft in load("ne_50m_glaciated_areas"):
        for poly in polygons(ft):
            r = poly_rings(poly[:1], 0.1, 0.6)
            if r:
                glaciers.append(r[0])
    report["glaciers"] = (len(glaciers), sum(len(r) // 2 for r in glaciers),
                          write_ts("glaciers", "Glaciers and ice sheets: one outline each, a flat [lon, lat, ...] array in degrees.", "GLACIERS: ReadonlyArray<ReadonlyArray<number>>", glaciers))

    for k, (n, v, size) in report.items():
        print("%-9s %5d shapes %7d vertices %8d bytes" % (k, n, v, size))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
